for (const [text, rows] of REFERENCE) {
  test(`the code for ${JSON.stringify(text.slice(0, 32))} is every module the reference makes`, () => {
    assert.deepEqual(qrRows(text), rows);
  });
}

test("the add code is what the phone's scanner reads: SAGEFIN-ADD:, then the add id, upper case", () => {
  const addId = "0199a1b2-c3d4-7e5f-8a9b-0c1d2e3f4a5b";
  // addDeviceQrText in the phone app's unlock_qr.dart, which parseAddDeviceCode reads.
  assert.equal(enrolmentQrText(addId), "SAGEFIN-ADD:0199A1B2-C3D4-7E5F-8A9B-0C1D2E3F4A5B");
  assert.equal(enrolmentQrText(addId).length, 48);
  // Upper case keeps it in alphanumeric mode: a 29 by 29 code, not a denser one.
  assert.equal(qrModules(enrolmentQrText(addId))?.length, 29);
  // The typed code beside it is the same id: eight groups of four.
  assert.equal(typedCode(addId), "0199 A1B2 C3D4 7E5F 8A9B 0C1D 2E3F 4A5B");
});

test("the three finder patterns and the dark module are where a reader looks for them", () => {
  const m = /** @type {boolean[][]} */ (qrModules(enrolmentQrText("0199a1b2-c3d4-7e5f-8a9b-0c1d2e3f4a5b")));
  const n = m.length;
  for (const [x, y] of [[0, 0], [n - 7, 0], [0, n - 7]]) {
    for (let d = 0; d < 7; d++) {
      assert.equal(m[y][x + d], true);
      assert.equal(m[y + 6][x + d], true);
      assert.equal(m[y + d][x], true);
      assert.equal(m[y + d][x + 6], true);
    }
    assert.equal(m[y + 1][x + 1], false);
    assert.equal(m[y + 3][x + 3], true);
  }
  assert.equal(m[n - 8][8], true);
});

test("anything too long for version 10 is no code, not a broken one", () => {
  assert.equal(qrModules("x".repeat(400)), null);
  assert.equal(qrRows("x".repeat(400)), null);
});
